package dev.auspex.corehub.audit;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.time.OffsetDateTime;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.argThat;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;

/** Feeds the raw pointer the scraper publishes, generated by pytest, to the raw audit. */
class RawAuditServiceTest {

    private final ObjectMapper mapper = new ObjectMapper();
    private JdbcTemplate jdbcTemplate;
    private RawAuditService service;

    @BeforeEach
    void setUp() {
        jdbcTemplate = mock(JdbcTemplate.class);
        service = new RawAuditService(jdbcTemplate, mapper);
    }

    @Test
    void test_generated_raw_pointer_records_audit_row_with_retrieved_at() throws Exception {
        String pointer = loadFixture();
        JsonNode fixture = mapper.readTree(pointer);

        service.record(pointer);

        verify(jdbcTemplate).update(
                anyString(),
                eq(fixture.get("raw_object_key").asText()),
                eq(fixture.get("source_type").asText()),
                eq(fixture.get("external_id").asText()),
                eq(fixture.get("content_sha256").asText()),
                argThat((Object at) -> at instanceof OffsetDateTime odt
                        && odt.isEqual(OffsetDateTime.parse(fixture.get("retrieved_at").asText()))));
    }

    @Test
    void test_raw_pointer_missing_retrieved_at_is_invalid() throws Exception {
        ObjectNode pointer = (ObjectNode) mapper.readTree(loadFixture());
        pointer.remove("retrieved_at");

        assertThatThrownBy(() -> service.record(pointer.toString()))
                .isInstanceOf(InvalidRawPointerException.class)
                .hasMessageContaining("retrieved_at");
        verify(jdbcTemplate, never()).update(anyString(), any(Object[].class));
    }

    @Test
    void test_raw_pointer_without_offset_is_invalid() throws Exception {
        ObjectNode pointer = (ObjectNode) mapper.readTree(loadFixture());
        pointer.put("retrieved_at", "2024-06-15T12:00:00");

        assertThatThrownBy(() -> service.record(pointer.toString()))
                .isInstanceOf(InvalidRawPointerException.class)
                .hasMessageContaining("retrieved_at");
        verify(jdbcTemplate, never()).update(anyString(), any(Object[].class));
    }

    private static String loadFixture() throws Exception {
        try (InputStream in = RawAuditServiceTest.class.getClassLoader()
                .getResourceAsStream("contract/raw_pointer_v1.json")) {
            assertThat(in).as("generated contract/raw_pointer_v1.json").isNotNull();
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
